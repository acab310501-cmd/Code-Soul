export function initLanguage() {
  const button = document.querySelector("[data-language-switcher]");
  if (!button) return;

  let currentLanguage = localStorage.getItem("code-soul-language") || "ru";

  function applyLanguage(language) {
    const data = translations[language];
    if (!data) return;

    document.documentElement.setAttribute("lang", language);

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const path = element.dataset.i18n.split(".");
      let value = data;
      path.forEach((key) => {
        value = value?.[key];
      });
      if (typeof value === "string") {
        element.innerHTML = value;
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      const path = element.dataset.i18nPlaceholder.split(".");
      let value = data;
      path.forEach((key) => {
        value = value?.[key];
      });
      if (typeof value === "string") {
        element.setAttribute("placeholder", value);
      }
    });

    document.querySelectorAll("[data-language]").forEach((element) => {
      element.classList.toggle(
        "language-switcher__active",
        element.dataset.language === language
      );
    });

    document.querySelectorAll("[data-pixel-text]").forEach((element) => {
      const key = element.dataset.i18n;
      if (!key) return;
      const path = key.split(".");
      let value = data;
      path.forEach((part) => {
        value = value?.[part];
      });
      if (typeof value === "string") {
        element.dataset.pixelText = value.replace(/<[^>]*>/g, "");
      }
    });

    localStorage.setItem("code-soul-language", language);
    currentLanguage = language;

    window.dispatchEvent(
      new CustomEvent("code-soul:language", {
        detail: { language },
      })
    );
  }

  button.addEventListener("click", () => {
    applyLanguage(currentLanguage === "ru" ? "en" : "ru");
  });

  applyLanguage(currentLanguage);
}

